# frozen_string_literal: true

# Writes Spinel's lib/spinel_rt_responds_generated.h to standard output
# with no Ruby interpreter: make spinel-header compiles this program with
# the installed Spinel and runs it on the checkout at SPINEL_REF.
#
#   gen_respond_to_tables SPINEL_SRC > spinel_rt_responds_generated.h
#
# Spinel's own generator, tools/gen_respond_to_tables.rb, is a CRuby
# script: it requires tools/builtin_row_gen.rb, which loads prism, json,
# and digest for its probes and does not compile with Spinel. The header
# needs only the part of the two files that reads text: the rows of
# src/builtin_ops.c's bop_rows[] and src/builtin_zero_ops.inc, the
# receiver families of builtin_row_gen.rb that serve them, and the
# hand-kept arrays of lib/spinel_rt.h. This program is that part, with
# the same patterns, exclusions, coverage checks, and output; it wrote
# the header that CRuby wrote at 001419ff byte for byte. A Spinel bump
# whose generator changes ports the change here in the same pull request.
module GenRespondToTables
  # The families the header holds an array for, in its order.
  FAMILIES = ["Array", "Hash", "String", "Integer", "Float"].freeze

  # builtin_row_gen.rb's FAMILIES: the bop_rows kinds each family serves,
  # in its order, for the families the header and the coverage checks
  # read. TY_POLY's rows are String's and Symbol's boxed faces.
  KINDS = {
    "Integer" => ["TY_INT", "BOP_IVAR_LESS"],
    "Float" => ["TY_FLOAT"],
    "String" => ["TY_STRING", "TY_POLY", "BOP_IVAR_LESS"],
    "Symbol" => ["TY_SYMBOL", "TY_POLY"],
    "Array" => ["BOP_ANY_ARRAY"],
    "Hash" => ["BOP_ANY_HASH"],
    "Range" => ["TY_RANGE"],
    "Range(Float)" => ["TY_FLOAT_RANGE"],
    "Range(String)" => ["TY_STR_RANGE"],
    "Proc" => ["TY_PROC"],
    "Exception" => ["TY_EXCEPTION"],
  }.freeze

  # Rows a family's kinds hold that are not that class's methods: the
  # two-argument pack is Array#pack's row under TY_POLY.
  FALSE_POSITIVE = { "String" => ["pack"] }.freeze

  # The hand-kept arrays sp_poly_responds_builtin already ORs in for
  # each family; a name they hold is not repeated in the generated one.
  SHARED_ARRAYS = {
    "Array" => ["uni", "enumm"],
    "Hash" => ["uni", "enumm"],
    "String" => ["uni"],
    "Integer" => ["uni", "numm"],
    "Float" => ["uni", "numm"],
  }.freeze

  RANGE_FAMILIES = ["Range", "Range(Float)", "Range(String)"].freeze
  RANGE_FALSE_POSITIVE = ["reverse", "join", "index"].freeze
  SYMBOL_FALSE_POSITIVE = ["dump", "undump", "pack"].freeze

  ROW = /\{\s*(\w+),\s*"((?:[^"\\]|\\.)*)",\s*(-?\w+),\s*(-?\w+),\s*(BF_\w+)/
  ZERO_IO = /\ABZ_IO\("([^"]+)",\s*\w+,\s*\w+,\s*(\d+)/
  ZERO_STR = /\ABZ_STR\("([^"]+)",\s*\w+,\s*\w+,\s*(\d+),\s*(\w+)/
  QUOTED = /"((?:[^"\\]|\\.)*)"/
  GATED = /strcmp\(m, "([^"]+)"\)/

  # One bop_rows row: the kind of receiver and the method name.
  class Row
    attr_reader :kind #: String
    attr_reader :name #: String

    #: (kind: String, name: String) -> void
    def initialize(kind:, name:)
      @kind = kind
      @name = name
    end
  end

  # The header's text for the checkout at root, or raises with what a
  # human has to add to lib/spinel_rt.h by hand.
  #: (String) -> String
  def self.generate(root)
    rows = rows_of(root)
    text = File.read(File.join(root, "lib/spinel_rt.h")).to_s
    uni = array_literal_names(text, "uni")
    enumm = array_literal_names(text, "enumm")
    numm = array_literal_names(text, "numm")
    check(rows, ["Proc"], uni + array_literal_names(text, "procm"), "Proc", "procm[]/uni[]", "procm[]")
    check(rows, RANGE_FAMILIES, uni + enumm + array_literal_names(text, "rngm") + RANGE_FALSE_POSITIVE, "Range", "rngm[]/enumm[]/uni[]", "rngm[]")
    check(rows, ["Symbol"], uni + array_literal_names(text, "symm") + SYMBOL_FALSE_POSITIVE, "Symbol", "symm[]/uni[]", "symm[]")
    check(rows, ["Exception"], uni + array_literal_names(text, "excm") + exception_gated_names(text), "Exception", "excm[]/the subclass-gating if-chain/uni[]", "excm[] or the if-chain")
    out = +"/* Generated by tools/gen_respond_to_tables.rb from src/builtin_ops.c's\n" \
           " * bop_rows[]. Do not edit by hand -- edit bop_rows[] and regenerate.\n" \
           " * See this script's own comments for the design rationale.\n" \
           " */\n"
    FAMILIES.each do |family|
      shared = []
      SHARED_ARRAYS.fetch(family).each do |array|
        shared.concat(uni) if array == "uni"
        shared.concat(enumm) if array == "enumm"
        shared.concat(numm) if array == "numm"
      end
      excluded = FALSE_POSITIVE.fetch(family, []) + shared
      names = family_names(rows, [family]).reject { |name| excluded.include?(name) }.sort.uniq
      out << "static const char *const sp_gen_responds_#{family.downcase}[] = {\n"
      names.each { |name| out << "  #{name.inspect},\n" }
      out << "  NULL\n};\n"
    end
    out
  end

  # builtin_row_gen.rb's rows: every bop_rows entry, then the BZ_IO and
  # BZ_STR lines of builtin_zero_ops.inc.
  #: (String) -> Array[untyped]
  def self.rows_of(root)
    path = File.join(root, "src/builtin_ops.c")
    src = File.read(path).to_s
    start = src.index("static const BuiltinOp bop_rows[] = {")
    raise "no bop_rows in #{path}" if start.nil?
    stop = src.index("\n};", start)
    raise "bop_rows in #{path} has no closing };" if stop.nil?
    out = []
    src[start...stop].to_s.scan(ROW).each do |match|
      out << Row.new(kind: match[0].to_s, name: unescape(match[1].to_s))
    end
    File.read(File.join(root, "src/builtin_zero_ops.inc")).to_s.each_line do |line|
      io = ZERO_IO.match(line)
      if io
        out << Row.new(kind: "TY_IO", name: io[1].to_s)
      else
        str = ZERO_STR.match(line)
        out << Row.new(kind: "TY_STRING", name: str[1].to_s) if str
      end
    end
    raise "no rows parsed" if out.size < 100
    out
  end

  # The names of the rows any of families serves, compiler-internal
  # names left out, each once.
  #: (Array[untyped], Array[String]) -> Array[String]
  def self.family_names(rows, families)
    names = []
    rows.each do |row|
      served = families.any? { |family| KINDS.fetch(family).include?(row.kind) }
      names << row.name if served && !internal?(row.name)
    end
    names.uniq
  end

  # builtin_row_gen.rb's INTERNAL_NAME, /\A__(?!.*__\z)/: a leading
  # double underscore not closed by another (__bivar_get, not __id__).
  #: (String) -> bool
  def self.internal?(name)
    name.start_with?("__") && !name[2, name.length - 2].to_s.end_with?("__")
  end

  # A family whose rows the hand-kept arrays must already cover.
  #: (Array[untyped], Array[String], Array[String], String, String, String) -> void
  def self.check(rows, families, covered, family, arrays, target)
    missing = family_names(rows, families).reject { |name| covered.include?(name) }
    return if missing.empty?

    raise "bop_rows now has #{family} method(s) #{arrays} in lib/spinel_rt.h don't cover: " \
          "#{missing.join(", ")}. Add them to #{target} by hand (#{family} is not generated)."
  end

  # The strcmp(m, "...") names of sp_poly_responds_builtin's Exception arm.
  #: (String) -> Array[String]
  def self.exception_gated_names(text)
    start = text.index("v.cls_id == SP_BUILTIN_EXCEPTION")
    raise "no Exception arm found in lib/spinel_rt.h" if start.nil?
    stop = text.index(/return 0;\s*\}/, start)
    raise "Exception arm in lib/spinel_rt.h has no closing `return 0; }`" if stop.nil?
    names = []
    text[start...stop].to_s.scan(GATED).each { |match| names << match[0].to_s }
    names.uniq
  end

  # The string literals of `static const char *const NAME[] = { ... };`.
  #: (String, String) -> Array[String]
  def self.array_literal_names(text, array_name)
    start = text.index("static const char *const #{array_name}[] = {")
    raise "no #{array_name}[] array found in lib/spinel_rt.h" if start.nil?
    stop = text.index("};", start)
    raise "#{array_name}[] array in lib/spinel_rt.h has no closing };" if stop.nil?
    names = []
    text[start...stop].to_s.scan(QUOTED).each { |match| names << unescape(match[0].to_s) }
    names
  end

  # A C string literal's body with each backslash escape read as the
  # character after it, as gsub(/\\(.)/, '\1') does.
  #: (String) -> String
  def self.unescape(text)
    return text unless text.include?("\\")

    out = +""
    index = 0
    while index < text.length
      char = text[index, 1].to_s
      if char == "\\" && index + 1 < text.length
        out << text[index + 1, 1].to_s
        index += 2
      else
        out << char
        index += 1
      end
    end
    out
  end

  #: (Array[String]) -> Integer
  def self.main(argv)
    if argv.size != 1
      warn "usage: gen_respond_to_tables SPINEL_SRC"
      return 2
    end
    print generate(argv[0].to_s)
    0
  rescue StandardError => e
    warn "gen_respond_to_tables: #{e.message}"
    1
  end
end

exit GenRespondToTables.main(ARGV)
